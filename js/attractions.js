  // Search attractions by text query, category, and province
  search(query = '', category = 'all', provinceId = 'all', userCoords = null) {
    let list = [...this.attractions];

    // Filter by province
    if (provinceId && provinceId !== 'all') {
      list = list.filter(item => item.provinceId === provinceId || item.province === provinceId);
    }

    // Filter by category
    if (category && category !== 'all') {
      list = list.filter(item => item.category === category);
    }

    // Filter by text query
    if (query && query.trim() !== '') {
      const q = query.trim().toLowerCase();
      list = list.filter(item => {
        const text = `${item.name} ${item.nameEn} ${item.province} ${item.desc} ${item.tags.join(' ')}`.toLowerCase();
        return text.includes(q);
      });
    }

    // Calculate distance if user coords provided
    const refLat = userCoords?.lat || window.mapManager?.userCoords?.lat || 13.7563;
    const refLng = userCoords?.lng || window.mapManager?.userCoords?.lng || 100.5018;

    list.forEach(item => {
      item.distanceKm = this.calcDistance(refLat, refLng, item.lat, item.lng);
    });

    // Sort by distance
    list.sort((a, b) => a.distanceKm - b.distanceKm);

    return list;
  }

  // Get nearby attractions within specified radius (default 50 km or top 10 closest)
  getNearby(maxDistKm = 100, userCoords = null) {
    const list = this.search('', 'all', 'all', userCoords);
    return list.filter(item => item.distanceKm <= maxDistKm).slice(0, 15);
  }

